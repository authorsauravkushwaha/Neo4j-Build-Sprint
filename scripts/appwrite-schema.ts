/**
 * Prints (or runs) the Appwrite provisioning commands for this project.
 *
 * Why a script rather than a checked-in `appwrite.json`: the CLI's declarative
 * attribute shape has changed between majors, and a command list can be diffed by
 * eye against `appwriteSchema.ts` — which is also what the adapter reads, so the
 * collections and the code cannot drift. The schema module owns the content; this
 * file owns the presentation and the exit code.
 *
 *   npm run appwrite:provision               # a copy-pasteable shell script
 *   npm run appwrite:provision -- --json     # machine-readable
 *   npm run appwrite:provision -- --run      # executes them (needs the CLI)
 *
 * `--run` is opt-in and never implied: these commands create a database in
 * somebody's project, and a script that does that by accident is a bad script.
 */
import { spawnSync } from 'node:child_process'

import { APPWRITE_DATABASE_ID, APPWRITE_COLLECTIONS, provisioningCommands } from '../supabase/functions/_shared/platform/appwriteSchema.ts'

interface Options {
  databaseId: string
  json: boolean
  run: boolean
  quiet: boolean
}

function parse(argv: string[]): Options {
  const options: Options = { databaseId: APPWRITE_DATABASE_ID, json: false, run: false, quiet: false }
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index]!
    if (arg === '--json') options.json = true
    else if (arg === '--run') options.run = true
    else if (arg === '--quiet') options.quiet = true
    else if (arg === '--database') {
      const value = argv[index + 1]
      if (!value) throw new Error('--database needs an id, e.g. --database graphmentor')
      options.databaseId = value
      index += 1
    } else if (arg === '--help' || arg === '-h') {
      console.log(USAGE)
      process.exit(0)
    } else {
      throw new Error(`Unknown argument: ${arg}`)
    }
  }
  return options
}

const USAGE = `Appwrite provisioning for GraphMentor AI.

Usage: npm run appwrite:provision -- [options]

  --database <id>   Database id (default: ${APPWRITE_DATABASE_ID})
  --json            Print the commands as JSON instead of a shell script
  --run             Execute the commands with the appwrite CLI (off by default)
  --quiet           Only errors
  -h, --help        This message

The commands are derived from supabase/functions/_shared/platform/appwriteSchema.ts,
which is the same file the adapter reads — the collections and the code cannot
drift. Every collection is created with no read/write permissions for any role:
the server API key is the only way in, and the browser never sees Appwrite.`

/** Shell-quotes a value so a copy-paste of the printed script is safe. */
function quote(value: string): string {
  if (/^[A-Za-z0-9._:@/=-]+$/.test(value)) return value
  return `'${value.replace(/'/g, `'\\''`)}'`
}

function main(): void {
  const options = parse(process.argv.slice(2))
  const commands = provisioningCommands(options.databaseId)

  if (options.json) {
    console.log(JSON.stringify({ databaseId: options.databaseId, collections: APPWRITE_COLLECTIONS.length, commands }, null, 2))
    return
  }

  if (!options.run) {
    if (!options.quiet) {
      console.log('#!/usr/bin/env bash')
      console.log('# Generated by `npm run appwrite:provision`. Each command is idempotent-ish:')
      console.log('# re-running it after a partial failure reports "already exists" and continues.')
      console.log('set -euo pipefail')
      console.log('')
      for (const command of commands) {
        console.log(`# ${command.why}`)
        console.log(command.argv.map(quote).join(' '))
      }
      console.log('')
      console.log(`# ${commands.length} commands. Add --run to execute them, or --json to build a pipeline.`)
    }
    return
  }

  for (const command of commands) {
    const [bin, ...args] = command.argv
    const result = spawnSync(bin!, args, { stdio: 'inherit', shell: false })
    if (result.error) {
      console.error(`\nCould not run \`${command.argv.join(' ')}\`: ${result.error.message}`)
      console.error('Install the Appwrite CLI (npm i -g appwrite-cli) and log in first: `appwrite login`.')
      process.exitCode = 1
      return
    }
    if (result.status !== 0) {
      // A collection or index that already exists is the common benign failure;
      // anything else should stop the run so the operator sees it.
      console.error(`\n\`${command.argv.join(' ')}\` exited ${result.status}. Stopping here.`)
      process.exitCode = 1
      return
    }
  }
  console.log(`\nProvisioned ${APPWRITE_COLLECTIONS.length} collections in database ${options.databaseId}.`)
  console.log('Set APPWRITE_ENDPOINT, APPWRITE_PROJECT_ID and APPWRITE_API_KEY as Edge Function secrets to switch backends.')
}

try {
  main()
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error))
  console.error('')
  console.error(USAGE)
  process.exitCode = 2
}
